export function normalizeSupport(value: string): string {
  return value
    .toLowerCase()
    .replace(/œ/g, "oe")
    .replace(/æ/g, "ae")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

function editDistance(a: string, b: string): number {
  if (a === b) return 0;
  if (Math.abs(a.length - b.length) > 2) return 3;
  const prev = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    let last = prev[0];
    prev[0] = i;
    for (let j = 1; j <= b.length; j++) {
      const keep = last + (a[i - 1] === b[j - 1] ? 0 : 1);
      last = prev[j];
      prev[j] = Math.min(prev[j] + 1, prev[j - 1] + 1, keep);
    }
  }
  return prev[b.length];
}

function keyScore(key: string, normalizedQuery: string, queryTokens: string[]): number {
  const k = normalizeSupport(key);
  if (!k) return 0;
  if (k.includes(" ")) return normalizedQuery.includes(k) ? 6 : 0;
  if (queryTokens.includes(k)) return 4;
  let best = 0;
  for (const token of queryTokens) {
    if (token.length >= 4 && (k.startsWith(token) || token.startsWith(k))) {
      best = Math.max(best, 2.5);
    } else if (
      k.length >= 4 &&
      k[0] === token[0] &&
      editDistance(k, token) <= (k.length >= 8 ? 2 : 1)
    ) {
      best = Math.max(best, 2);
    }
  }
  return best;
}

export function answerSupport(query: string, lang: Lang): SupportAnswer {
  const normalized = normalizeSupport(query);
  const tokens = normalized.split(" ").filter(Boolean);
  let best: Entry | null = null;
  let bestScore = 0;
  if (tokens.length) {
    // ponytail: best key wins, not the sum — summing let two vague keys outrank one exact
    // phrase ("messages prives" matched the messages page). Per-topic scores if that ever bites.
    for (const entry of KB) {
      let score = 0;
      for (const key of entry.keys) score = Math.max(score, keyScore(key, normalized, tokens));
      if (score > bestScore) {
        bestScore = score;
        best = entry;
      }
    }
  }
  if (!best || bestScore < 1.8) {
    return { text: FALLBACK[lang], to: "/contact-us", link: FALLBACK_LINK[lang], matched: false };
  }
  return { text: best.text[lang], to: best.to, link: best.link?.[lang], matched: true };
}

export function fuzzyMatches(text: string, query: string): boolean {
  const hay = normalizeSupport(text);
  const q = normalizeSupport(query);
  if (!q) return true;
  if (hay.includes(q)) return true;
  const hayTokens = hay.split(" ").filter(Boolean);
  const queryTokens = q.split(" ").filter(Boolean);
  const hits = queryTokens.filter((token) =>
    hayTokens.some((word) => {
      if (word === token) return true;
      if (token.length >= 3 && (word.startsWith(token) || token.startsWith(word))) return true;
      return (
        token.length >= 4 &&
        word[0] === token[0] &&
        editDistance(word, token) <= (token.length >= 8 ? 2 : 1)
      );
    }),
  ).length;
  return hits / Math.max(1, queryTokens.length) >= 0.6;
}
