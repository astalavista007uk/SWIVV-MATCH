export function getProfile(id: string) {
  return SWIVV_PROFILES.find((p) => p.id === id);
}

const photoUrl = (id: string) =>
  `https://images.unsplash.com/${id}?auto=format&fit=crop&crop=faces&w=600&q=80`;

/** Portrait choices for the signup photo picker (full URLs). */
export function swivvPhotoChoices(gender: "woman" | "man"): string[] {
  return (gender === "woman" ? WOMEN : MEN).map(photoUrl);
}

/** Total children in the member's family (siblings + the member). */
export function siblingTotal(p: SwivvProfile): number {
  return (p.brothersCount ?? 0) + (p.sistersCount ?? 0) + 1;
}

/** e.g. "2 frères, 1 sœur (4 enfants au total)" or "Enfant unique". */
export function siblingSummary(p: SwivvProfile): string {
  const b = p.brothersCount ?? 0;
  const s = p.sistersCount ?? 0;
  if (b === 0 && s === 0) return "Enfant unique";
  const parts: string[] = [];
  if (b > 0) parts.push(`${b} frère${b > 1 ? "s" : ""}`);
  if (s > 0) parts.push(`${s} sœur${s > 1 ? "s" : ""}`);
  const total = siblingTotal(p);
  return `${parts.join(", ")} (${total} enfant${total > 1 ? "s" : ""} au total)`;
}

/** "Animaux": e.g. "Oui (1 chien)" or "Non". Details blank ("—") when no pets. */
export function petsLabel(p: SwivvProfile): string {
  if ((p.hasPets ?? "Non").toLowerCase().startsWith("oui")) {
    const d = (p.petsDetails ?? "").trim();
    return d && d !== "—" ? `Oui (${d})` : "Oui";
  }
  return "Non";
}

